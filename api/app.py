@dataclass(frozen=True)
class Settings:
    data_dir: Path
    origin: str
    workflow_key: str
    reviewer_key: str
    session_key: str
    webhook_url: str = 'http://n8n:5678/webhook/production-plan'
    secure_cookies: bool = False
    session_limit: int = 5
    ip_limit: int = 10
    daily_limit: int = 40
    job_ttl: int = 1800
    planning_timeout: int = 180
    database_url: str | None = None
    database_prefix: str = 'production_desk'

    @classmethod
    def from_env(cls):
        values = [os.environ.get(name, '') for name in ('WORKFLOW_SERVICE_TOKEN', 'REVIEWER_SECRET', 'SESSION_SECRET')]
        if any(len(value) < 32 for value in values):
            raise RuntimeError('Run scripts/setup.py to create the three server secrets before starting the gateway.')
        origin = os.environ.get('PUBLIC_ORIGIN', 'http://localhost:8088').rstrip('/')
        return cls(Path(os.environ.get('DEMO_DATA_DIR', '/data')), origin, *values,
                   webhook_url=os.environ.get('N8N_WEBHOOK_URL', 'http://n8n:5678/webhook/production-plan'),
                   secure_cookies=origin.startswith('https://'),
                   database_url=os.environ.get('DATABASE_URL'),
                   database_prefix=os.environ.get('DATABASE_PREFIX', 'production_desk'))


class Submission(QuoteInput):
    # Generated by the gateway; the browser cannot select someone else's ID.
    request_id: str = 'gateway-generated'
    budget_sar: int = Field(strict=True, ge=1, le=1_000_000)


class BrowserSubmission(StrictBody):
    brief: str = Field(min_length=10, max_length=4000)
    production_date: str
    duration_hours: int = Field(strict=True, ge=1, le=8)
    camera_count: int = Field(strict=True, ge=1, le=3)
    include_audio: bool = Field(strict=True)
    editing_hours: int = Field(strict=True, ge=0, le=8)
    budget_sar: int = Field(strict=True, ge=1, le=1_000_000)


class PlanningResult(StrictBody):
    status: Literal['awaiting_review', 'rejected', 'error', 'needs_info']
    quote_id: str | None = Field(default=None, max_length=80)
    claimed_total_sar: int | None = Field(default=None, strict=True, ge=0)
    brief_summary: str = Field(default='', max_length=4000)
    agent_tool_sequence: list[str] = Field(default_factory=list, max_length=3)


class Decision(StrictBody):
    decision: Literal['approved', 'denied']


def digest(value: str):
    return hashlib.sha256(value.encode()).hexdigest()


def create_app(settings: Settings | None = None, dispatcher=None, clock=time.time) -> FastAPI:
    settings = settings or Settings.from_env()
    settings.data_dir.mkdir(parents=True, exist_ok=True)
    database = settings.data_dir / 'sessions.sqlite3'
    erp = create_erp(settings.data_dir / 'erp.sqlite3', settings.reviewer_key,
                     database_url=settings.database_url, database_prefix=settings.database_prefix)
    app = FastAPI(title='Production Desk', version='2.0.0', docs_url=None, redoc_url=None, openapi_url=None)

    @contextmanager
    def connect():
        with database_connect(database, 'gateway', settings.database_url, settings.database_prefix) as conn:
            yield conn

    with connect() as conn:
        conn.execute('PRAGMA journal_mode=WAL')
        conn.executescript('''
            CREATE TABLE IF NOT EXISTS sessions (owner TEXT PRIMARY KEY, expires REAL NOT NULL);
            CREATE TABLE IF NOT EXISTS jobs (
                id TEXT PRIMARY KEY, owner TEXT NOT NULL, ip_hash TEXT NOT NULL,
                payload TEXT NOT NULL, status TEXT NOT NULL, result TEXT,
                decision TEXT, created REAL NOT NULL, updated REAL NOT NULL
            );
            CREATE INDEX IF NOT EXISTS jobs_owner_created ON jobs(owner, created);
        ''')

    async def erp_call(method, path, **kwargs):
        async with httpx.AsyncClient(transport=httpx.ASGITransport(app=erp), base_url='http://erp') as client:
            return await client.request(method, path, **kwargs)

    def csrf(token):
        return hmac.new(settings.session_key.encode(), token.encode(), hashlib.sha256).hexdigest()

    def owner(request: Request, mutate=False):
        token = request.cookies.get('production_session', '')
        if not re.fullmatch(r'[A-Za-z0-9_-]{43}', token):
            raise HTTPException(401, 'ابدأ جلسة جديدة من الصفحة الرئيسية.')
        hashed = digest(token)
        with connect() as conn:
            session = conn.execute('SELECT expires FROM sessions WHERE owner=?', (hashed,)).fetchone()
        if not session or session['expires'] <= clock():
            raise HTTPException(401, 'انتهت الجلسة. حدّث الصفحة للبدء من جديد.')
        if mutate:
            if request.headers.get('origin') != settings.origin or not hmac.compare_digest(request.headers.get('x-csrf-token', '').encode(), csrf(token).encode()):
                raise HTTPException(403, 'تعذّر التحقق من مصدر الطلب. حدّث الصفحة وحاول مجددًا.')
        return hashed

    def trusted(request):
        if not hmac.compare_digest(request.headers.get('x-workflow-key', '').encode(), settings.workflow_key.encode()):
            raise HTTPException(403, 'Workflow authentication required')

    def owned_job(job_id, hashed_owner):
        with connect() as conn:
            row = conn.execute('SELECT * FROM jobs WHERE id=? AND owner=?', (job_id, hashed_owner)).fetchone()
        if not row:
            raise HTTPException(404, 'الطلب غير موجود في هذه الجلسة.')
        if row['created'] + settings.job_ttl <= clock():
            raise HTTPException(410, 'انتهت صلاحية الطلب. أنشئ طلبًا جديدًا.')
        return row

    def error_result(message):
        return {'status': 'error', 'message': message, 'synthetic': True}

    def fail_pending(job_id, message):
        with connect() as conn:
            conn.execute("UPDATE jobs SET status='error',result=?,updated=? WHERE id=? AND status='planning'",
                         (json.dumps(error_result(message), ensure_ascii=False), clock(), job_id))

    async def dispatch(job_id, payload):
        try:
            if dispatcher:
                await dispatcher(payload)
            else:
                async with httpx.AsyncClient(timeout=10, trust_env=False) as client:
                    response = await client.post(settings.webhook_url, json=payload, headers={'X-Workflow-Key': settings.workflow_key})
                    response.raise_for_status()
        except Exception:
            # No provider errors, request body, internal URLs or credentials reach the browser.
            fail_pending(job_id, 'خدمة التخطيط غير متاحة حاليًا. حاول مرة أخرى لاحقًا.')

    @app.middleware('http')
    async def boundary(request, call_next):
        size = request.headers.get('content-length', '')
        if size and (not size.isdecimal() or int(size) > 20_000):
            return JSONResponse({'detail': 'الطلب أكبر من الحجم المسموح.'}, status_code=413)
        # Streaming requests are also bounded; do not rely only on Content-Length.
        if request.method == 'POST':
            content = await request.body()
            if len(content) > 20_000:
                return JSONResponse({'detail': 'الطلب أكبر من الحجم المسموح.'}, status_code=413)
        response = await call_next(request)
        response.headers['X-Content-Type-Options'] = 'nosniff'
        response.headers['Referrer-Policy'] = 'same-origin'
        response.headers['Content-Security-Policy'] = "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; connect-src 'self'; frame-ancestors 'none'; base-uri 'self'; form-action 'self'"
        if request.url.path.startswith('/api/'):
            response.headers['Cache-Control'] = 'no-store'
        return response

    @app.exception_handler(Exception)
    async def internal_error(request, exc):
        return JSONResponse({'detail': 'تعذّر إكمال الطلب. حاول مرة أخرى لاحقًا.'}, status_code=500)

    @app.get('/health')
    def health():
        return {'status': 'ok', 'synthetic': True}

    @app.get('/api/session')
    def start_session(request: Request, response: Response):
        token = request.cookies.get('production_session', '')
        try:
            owner(request)
        except HTTPException:
            token = secrets.token_urlsafe(32)
            with connect() as conn:
                conn.execute('DELETE FROM sessions WHERE expires<=?', (clock(),))
                conn.execute('INSERT INTO sessions VALUES (?,?)', (digest(token), clock() + 3600))
            response.set_cookie('production_session', token, httponly=True, samesite='strict', secure=settings.secure_cookies, max_age=3600, path='/')
        return {'csrf_token': csrf(token), 'today': date.today().isoformat(), 'synthetic': True}

    @app.post('/api/jobs', status_code=202)
    async def submit(body: BrowserSubmission, request: Request, tasks: BackgroundTasks):
        hashed = owner(request, mutate=True)
        job_id = 'job_' + uuid.uuid4().hex
        try:
            payload = Submission(request_id=job_id, **body.model_dump()).model_dump()
        except ValueError:
            raise HTTPException(422, 'اختر تاريخًا صالحًا خلال السنة القادمة.') from None
        address = request.headers.get('x-real-ip') or (request.client.host if request.client else 'local')
        ip_hash = hmac.new(settings.session_key.encode(), address.encode(), hashlib.sha256).hexdigest()
        now = clock()
        with connect() as conn:
            conn.execute('BEGIN IMMEDIATE')
            conn.execute('DELETE FROM jobs WHERE created<?', (now - 86400,))
            # Timed-out executions cannot indefinitely hold the single planning slot.
            conn.execute("UPDATE jobs SET status='error',result=?,updated=? WHERE status='planning' AND created<?",
                         (json.dumps(error_result('انتهت مهلة التخطيط. أنشئ طلبًا جديدًا.'), ensure_ascii=False), now, now - settings.planning_timeout))
            session_count = conn.execute('SELECT COUNT(*) FROM jobs WHERE owner=? AND created>?', (hashed, now - 3600)).fetchone()[0]
            ip_count = conn.execute('SELECT COUNT(*) FROM jobs WHERE ip_hash=? AND created>?', (ip_hash, now - 3600)).fetchone()[0]
            daily_count = conn.execute('SELECT COUNT(*) FROM jobs WHERE created>?', (now - 86400,)).fetchone()[0]
            if session_count >= settings.session_limit or ip_count >= settings.ip_limit or daily_count >= settings.daily_limit:
                raise HTTPException(429, 'وصلت التجربة لحد الطلبات المتاح. جرّب لاحقًا.')
            if conn.execute("SELECT 1 FROM jobs WHERE status='planning'").fetchone():
                raise HTTPException(429, 'يتم تجهيز طلب آخر الآن. انتظر قليلًا ثم حاول مجددًا.')
            conn.execute('INSERT INTO jobs VALUES (?,?,?,?,?,?,?,?,?)',
                         (job_id, hashed, ip_hash, json.dumps(payload, ensure_ascii=False), 'planning', None, None, now, now))
            conn.commit()
        tasks.add_task(dispatch, job_id, payload)
        return {'id': job_id, 'status': 'planning', 'synthetic': True}

    @app.get('/api/jobs/{job_id}')
    def get_job(job_id: str, request: Request):
        row = owned_job(job_id, owner(request))
        if row['status'] == 'planning' and row['created'] + settings.planning_timeout <= clock():
            fail_pending(job_id, 'انتهت مهلة التخطيط. أنشئ طلبًا جديدًا.')
            row = owned_job(job_id, owner(request))
        result = json.loads(row['result']) if row['result'] else {'status': row['status'], 'synthetic': True}
        return {'id': job_id, **result, 'status': row['status']}

    @app.api_route('/internal/erp/{path:path}', methods=['GET', 'POST'])
    async def planning_tool(path: str, request: Request):
        trusted(request)
        allowed = ((request.method == 'GET' and (path in ('catalog', 'availability') or re.fullmatch(r'quotes/q_[a-f0-9]{32}', path)))
                   or (request.method == 'POST' and path in ('quotes', 'quotes/verify')))
        if not allowed:
            raise HTTPException(404, 'Planning tool not found')
        response = await erp_call(request.method, '/' + path, params=request.query_params,
                                  content=await request.body(), headers={'Content-Type': 'application/json'})
        return JSONResponse(response.json(), status_code=response.status_code)

    @app.post('/internal/jobs/{job_id}/result')
    async def receive_result(job_id: str, body: PlanningResult, request: Request):
        trusted(request)
        with connect() as conn:
            row = conn.execute('SELECT * FROM jobs WHERE id=?', (job_id,)).fetchone()
        if not row:
            raise HTTPException(404, 'Job not found')
        if row['status'] != 'planning':
            return {'accepted': True, 'status': row['status']}  # Callback retry cannot replace a decision.
        if row['created'] + settings.planning_timeout <= clock():
            fail_pending(job_id, 'انتهت مهلة التخطيط. أنشئ طلبًا جديدًا.')
            raise HTTPException(410, 'Planning result arrived after deadline')
        result = error_result('تعذّر التحقق من عرض السعر. لم يتم إنشاء أمر عمل.')
        if body.status in ('awaiting_review', 'rejected') and body.quote_id and body.claimed_total_sar is not None and body.agent_tool_sequence == ['catalog', 'availability', 'quote']:
            canonical_response = await erp_call('POST', '/quotes/verify', json={'quote_id': body.quote_id, 'claimed_total_sar': body.claimed_total_sar})
            if canonical_response.status_code == 200:
                quote = canonical_response.json()['quote']
                payload = json.loads(row['payload'])
                expected_fields = {k: payload[k] for k in ('request_id', 'brief', 'production_date', 'duration_hours', 'camera_count', 'include_audio', 'editing_hours')}
                reconciles = sum(item['line_total_sar'] for item in quote['line_items']) == quote['total_sar']
                if quote['fields'] == expected_fields and quote['request_id'] == job_id and quote['synthetic'] is True and quote['currency'] == 'SAR' and reconciles:
                    status = 'awaiting_review'
                    message = 'راجع العرض، ثم اختر الموافقة أو الرفض.'
                    if not quote['available']:
                        status, message = 'rejected', 'الموارد غير متاحة للتاريخ أو العدد المطلوب.'
                    elif quote['total_sar'] > payload['budget_sar']:
                        status, message = 'rejected', f"العرض {quote['total_sar']} SAR يتجاوز الميزانية {payload['budget_sar']} SAR."
                    result = {'status': status, 'message': message, 'quote': quote, 'plan': body.brief_summary,
                              'tools': body.agent_tool_sequence, 'synthetic': True}
        with connect() as conn:
            conn.execute("UPDATE jobs SET status=?,result=?,updated=? WHERE id=? AND status='planning'",
                         (result['status'], json.dumps(result, ensure_ascii=False), clock(), job_id))
        return {'accepted': True, 'status': result['status']}

    @app.post('/api/jobs/{job_id}/decision')
    async def decide(job_id: str, body: Decision, request: Request):
        hashed = owner(request, mutate=True)
        row = owned_job(job_id, hashed)
        with connect() as conn:
            conn.execute('BEGIN IMMEDIATE')
            current = conn.execute('SELECT * FROM jobs WHERE id=? AND owner=?', (job_id, hashed)).fetchone()
            if current['status'] in ('created', 'denied'):
                if current['decision'] != body.decision:
                    raise HTTPException(409, 'الطلب له قرار نهائي بالفعل.')
                return json.loads(current['result'])
            if current['status'] == 'reviewing':
                raise HTTPException(409, 'القرار قيد التنفيذ. انتظر النتيجة.')
            if current['status'] != 'awaiting_review':
                raise HTTPException(409, 'هذا الطلب غير قابل للمراجعة.')
            result = json.loads(current['result'])
            conn.execute("UPDATE jobs SET status='reviewing',decision=?,updated=? WHERE id=?", (body.decision, clock(), job_id))
            conn.commit()
        try:
            # The browser supplies only a decision. Quote IDs, tokens, and totals stay server-owned.
            review = await erp_call('POST', '/reviews', json={'quote_id': result['quote']['quote_id'], 'decision': body.decision},
                                    headers={'X-Reviewer-Key': settings.reviewer_key})
            review.raise_for_status()
            if body.decision == 'denied':
                result.update(status='denied', message='تم رفض العرض. لم يتم إنشاء أمر عمل.')
            else:
                canonical_review = review.json()
                order_response = await erp_call('POST', '/work-orders', json={'quote_id': result['quote']['quote_id'],
                    'approval_token': canonical_review['approval_token'], 'idempotency_key': 'order-' + job_id})
                order_response.raise_for_status()
                order = order_response.json()
                if order['request_id'] != job_id or order['quote_id'] != result['quote']['quote_id'] or order['quote'] != result['quote'] or order['synthetic'] is not True or order['status'] != 'created':
                    raise ValueError('Unexpected work order result')
                result.update(status='created', message='تم إنشاء أمر العمل التجريبي بعد موافقتك.', order=order)
            with connect() as conn:
                conn.execute('UPDATE jobs SET status=?,result=?,updated=? WHERE id=?',
                             (result['status'], json.dumps(result, ensure_ascii=False), clock(), job_id))
            return result
        except Exception:
            # Never report success after an uncertain write. No automatic new review/token is issued.
            with connect() as conn:
                conn.execute("UPDATE jobs SET status='error',result=?,updated=? WHERE id=?",
                             (json.dumps(error_result('تعذّر إكمال تسجيل القرار. لا تعد إرسال قرار جديد لهذا الطلب.'), ensure_ascii=False), clock(), job_id))
            raise HTTPException(503, 'تعذّر إكمال تسجيل القرار. راجع نتيجة الطلب.') from None

    web = Path(__file__).resolve().parent.parent / 'web'
    if (web / 'index.html').exists():
        app.mount('/assets', StaticFiles(directory=web / 'assets'), name='assets')

        @app.get('/', include_in_schema=False)
        def index():
            return FileResponse(web / 'index.html')

    app.state.settings = settings
    app.state.erp = erp
    return app
